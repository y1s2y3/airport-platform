/** 验评目录树：仅工程层级节点（单位工程～检验批）；名称不含类型文案，由 UI 用标签展示 */
export function buildWbsTree(project_id) {
  let list = wbsNodes.filter((n) => WBS_TREE_NODE_TYPES.includes(n.node_type))
  if (project_id) list = list.filter((n) => n.project_id === project_id)
  const map = new Map()
  list.forEach((n) => {
    map.set(n.id, {
      id: n.id,
      label: n.node_name,
      node_type: n.node_type,
      type_label: WBS_TREE_NODE_TYPE_LABEL[n.node_type] || String(n.node_type),
      raw: n,
      children: [],
    })
  })
  const roots = []
  list.forEach((n) => {
    const node = map.get(n.id)
    if (n.parent_id && map.has(n.parent_id)) map.get(n.parent_id).children.push(node)
    else roots.push(node)
  })
  const bySort = (a, b) => (a.raw?.sort_no || 0) - (b.raw?.sort_no || 0)
  const sortDeep = (nodes) => {
    nodes.sort(bySort)
    nodes.forEach((n) => n.children?.length && sortDeep(n.children))
  }
  sortDeep(roots)
  return roots
}

