export function getControlPlansForProject(projectId) {
  const matched = CONTROL_PLANS.filter((plan) => plan.projectIds.includes(projectId))
  if (matched.length) return matched
  return CONTROL_PLANS.filter((plan) => plan.projectIds.includes('p-000')).slice(0, 2)
}

export function enrichControlPlan(plan) {
  const nodes = plan.status.map((rawStatus, index) => {
    const parsed = parseControlNodeStatus(rawStatus)
    const kind = resolveControlNodeKind(parsed.kind, plan.planEnd[index])
    return {
      index,
      planStart: plan.planStart[index],
      planEnd: plan.planEnd[index],
      owner: plan.owner[index],
      statusRaw: rawStatus,
      statusKind: kind,
      statusLabel: parsed.label,
      progress: parsed.progress,
      workProgress: plan.workProgress[index],
      remark: plan.remark[index],
    }
  })
  return { ...plan, nodes }
}

export function getControlPlanStats(plans) {
  const stats = { total: 0, pending: 0, active: 0, done: 0, lag: 0, na: 0 }
  plans.forEach((plan) => {
    enrichControlPlan(plan).nodes.forEach((node) => {
      if (node.statusKind === 'na' || node.statusKind === 'empty') return
      stats.total += 1
      if (stats[node.statusKind] !== undefined) stats[node.statusKind] += 1
    })
  })
  return stats
}

export function getControlPlanSummary(plans) {
  const stats = getControlPlanStats(plans)
  const planCount = plans.length
  const lagPlans = plans.reduce((sum, p) => sum + (p.lagCount || 0), 0)
  const avgCompletion = planCount
    ? Math.round((plans.reduce((s, p) => s + p.completionRate, 0) / planCount) * 100) / 100
    : 0
  return { ...stats, planCount, lagPlans, avgCompletion }
}
