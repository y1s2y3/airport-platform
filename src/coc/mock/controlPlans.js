import {
  CONTROL_PLAN_NODE_COUNT,
  parseControlNodeStatus,
  resolveControlNodeKind,
} from './controlPlanSchema.js'

function cp({
  id,
  projectIds,
  name,
  currentStages = [],
  completionRate = 0,
  lagCount = 0,
  planStart = [],
  planEnd = [],
  owner = [],
  status = [],
  workProgress = [],
  remark = [],
}) {
  const pad = (arr) => {
    const next = [...arr]
    while (next.length < CONTROL_PLAN_NODE_COUNT) next.push('-')
    return next.slice(0, CONTROL_PLAN_NODE_COUNT)
  }
  return {
    id,
    projectIds,
    name,
    currentStages,
    completionRate,
    lagCount,
    planStart: pad(planStart),
    planEnd: pad(planEnd),
    owner: pad(owner),
    status: pad(status),
    workProgress: pad(workProgress),
    remark: pad(remark),
  }
}

